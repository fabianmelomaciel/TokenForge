"""Python handle template.

Every forged handle is standard-library only, deterministic by default, reads a
JSON object from ``--json`` (or stdin with ``-``), writes one JSON object to
stdout and exposes ``--selftest`` and ``--dry-run``.
"""

from __future__ import annotations

import re
from typing import List, Optional

from .version import VERSION

_TEMPLATE = '''#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""TokenForge handle: __NAME__

TASK:
__TASK_DOC__

USAGE:
    python .forge/handles/__NAME__.py --json '{"name": "world"}'
    python .forge/handles/__NAME__.py --json - < input.json
    python .forge/handles/__NAME__.py --selftest
    python .forge/handles/__NAME__.py --dry-run

SAFETY:
    Deterministic, standard library only. No network by default.
    No eval/exec and no shell=True. Review this file before relying on it.

Generated by TokenForge __VERSION__.
Task signature: __SIGNATURE__
Tags: __TAGS_TEXT__
Danger: __DANGER__
"""
from __future__ import annotations

import argparse
import json
import sys

HANDLE_NAME = __NAME_REPR__
TASK = __TASK_REPR__
TAGS = __TAGS_REPR__
DANGER = __DANGER_REPR__


def handle(payload: dict, dry_run: bool = False) -> dict:
    """Return a JSON-serializable result for one deterministic task.

    ``payload`` is the object parsed from --json. Return a dict.
    This default implementation greets a name; replace the body with the
    deterministic logic described by TASK, then update _selftest().
    """
    name = payload.get("name", "world")
    if not isinstance(name, str):
        raise ValueError("'name' must be a string")
    result = {"ok": True, "message": "Hello, {}!".format(name)}
    if dry_run:
        result["dry_run"] = True
    return result


def _read_payload(raw: str) -> dict:
    """Parse a JSON object from a string or from stdin when raw is '-'."""
    if raw == "-":
        raw = sys.stdin.read()
    if raw is None or not str(raw).strip():
        return {}
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError("invalid JSON input: {}".format(exc))
    if not isinstance(data, dict):
        raise ValueError("JSON input must be an object")
    return data


def _selftest_fail(payload: dict, detail: str = "") -> int:
    """Print a JSON selftest failure and return 1."""
    message = "selftest failed for payload {!r}".format(payload)
    if detail:
        message += ": " + detail
    print(json.dumps({"ok": False, "error": message}, ensure_ascii=False), file=sys.stderr)
    return 1


def _selftest() -> int:
    """Run deterministic checks for the default implementation."""
    checks = [
        ({}, True),
        ({"name": "TokenForge"}, True),
        ({"name": 7}, False),
    ]
    for payload, should_pass in checks:
        try:
            result = handle(payload)
        except ValueError:
            if should_pass:
                return _selftest_fail(payload, "unexpected ValueError")
            continue
        except Exception as exc:  # pragma: no cover - defensive
            return _selftest_fail(payload, "{}: {}".format(type(exc).__name__, exc))
        if not should_pass:
            return _selftest_fail(payload, "expected ValueError")
        if not isinstance(result, dict) or result.get("ok") is not True:
            return _selftest_fail(payload, "expected a dict with ok=True")
    print(
        json.dumps(
            {"ok": True, "selftest": "passed", "handle": HANDLE_NAME},
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0


def main(argv=None) -> int:
    """CLI entry point. Exit codes: 0 ok, 1 runtime error, 2 usage error."""
    parser = argparse.ArgumentParser(
        description="TokenForge handle: {}".format(HANDLE_NAME)
    )
    parser.add_argument(
        "--json",
        default="{}",
        metavar="JSON",
        help="JSON object to process, or '-' to read from stdin",
    )
    parser.add_argument("--selftest", action="store_true", help="run built-in checks")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="validate input without producing side effects",
    )
    parser.add_argument(
        "extra",
        nargs="*",
        metavar="ARG",
        help="optional extra arguments exposed as payload['_args']",
    )
    args, unknown = parser.parse_known_args(argv)

    if args.selftest:
        return _selftest()

    try:
        payload = _read_payload(args.json)
        extra_args = list(args.extra) + list(unknown)
        if extra_args:
            payload.setdefault("_args", extra_args)
        result = handle(payload, dry_run=args.dry_run)
        if not isinstance(result, dict):
            result = {"ok": True, "result": result}
        print(json.dumps(result, ensure_ascii=False, sort_keys=True))
        return 0
    except ValueError as exc:
        print(
            json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False),
            file=sys.stderr,
        )
        return 2
    except Exception as exc:  # pragma: no cover - defensive
        print(
            json.dumps(
                {"ok": False, "error": "{}: {}".format(type(exc).__name__, exc)},
                ensure_ascii=False,
            ),
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
'''


_PLACEHOLDER = re.compile(
    r"__(?:VERSION|SIGNATURE|NAME_REPR|NAME|TAGS_TEXT|TAGS_REPR|"
    r"DANGER_REPR|DANGER|TASK_DOC|TASK_REPR)__"
)


def _task_doc(task: str) -> str:
    """Render a task description as an indented docstring block.

    Backslashes are escaped so a task such as ``read C:\\Users\\me\\file.txt``
    cannot become a Python escape sequence (``\\U``, ``\\N``, ...) that breaks
    the generated source. The rendered docstring still shows the original text.
    """
    text = str(task or "").strip() or "(no description)"
    text = text.replace("\\", "\\\\")
    text = text.replace('"""', "'''")
    return "\n".join("    " + line for line in text.splitlines())


def render_handle(
    name: str,
    task: str,
    tags: Optional[List[str]] = None,
    danger: bool = False,
    signature: str = "",
    version: str = VERSION,
) -> str:
    """Render a complete Python handle source file.

    Substitution is a single pass over the template: values inserted for a
    placeholder (in particular the user-supplied task) are never re-scanned for
    other placeholders. A task that happens to contain ``__TASK_REPR__`` or
    ``__NAME__`` therefore cannot corrupt the generated source.
    """
    tags = list(tags or [])
    replacements = {
        "__VERSION__": version,
        "__SIGNATURE__": signature or "(not computed)",
        "__NAME_REPR__": repr(name),
        "__NAME__": name,
        "__TAGS_TEXT__": ", ".join(tags) if tags else "(none)",
        "__TAGS_REPR__": repr(tags),
        "__DANGER_REPR__": "True" if danger else "False",
        "__DANGER__": "yes" if danger else "no",
        "__TASK_DOC__": _task_doc(task),
        "__TASK_REPR__": repr(str(task)),
    }
    return _PLACEHOLDER.sub(lambda match: replacements[match.group(0)], _TEMPLATE)
